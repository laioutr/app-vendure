const byLanguage: Record<string, CheckoutMessages> = { en, de, fr, nl, es, it, pl };

/** The messages for a language code (`de`, `de-CH`); English for any language the app does not carry. */
export const messagesFor = (languageCode: string | undefined): CheckoutMessages =>
  byLanguage[(languageCode ?? '').toLowerCase().split('-')[0] ?? ''] ?? en;

/** Fills `{name}` placeholders; an unknown placeholder stays as written. */
export const fill = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
